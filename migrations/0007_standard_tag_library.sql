    tag_id TEXT PRIMARY KEY, name TEXT NOT NULL, dimension TEXT NOT NULL, category TEXT NOT NULL DEFAULT '',
    parent_id TEXT, description TEXT NOT NULL DEFAULT '', status TEXT NOT NULL DEFAULT 'active'
  );
