  CREATE UNIQUE INDEX IF NOT EXISTS idx_standard_tag_alias_unique ON standard_tag_aliases(tag_id, alias);
  CREATE TABLE IF NOT EXISTS book_standard_tags (
    book_id TEXT NOT NULL, tag_id TEXT NOT NULL, PRIMARY KEY (book_id, tag_id)
