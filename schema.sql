-- CF-Book 原型数据库结构（Cloudflare D1 / SQLite）
CREATE TABLE IF NOT EXISTS uploads (
  upload_id    TEXT PRIMARY KEY,
  filename     TEXT NOT NULL,
  mime         TEXT NOT NULL DEFAULT 'application/octet-stream',
  total_size   INTEGER NOT NULL,
  chunk_size   INTEGER NOT NULL DEFAULT 8388608,
  total_chunks INTEGER NOT NULL,
  sha256       TEXT NOT NULL DEFAULT '',
  status       TEXT NOT NULL DEFAULT 'active',
  owner        TEXT NOT NULL DEFAULT '',
  created_at   INTEGER NOT NULL,
  updated_at   INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS chunks (
  upload_id     TEXT NOT NULL,
  idx           INTEGER NOT NULL,
  size          INTEGER NOT NULL DEFAULT 0,
  sha256        TEXT NOT NULL DEFAULT '',
  status        TEXT NOT NULL DEFAULT 'pending',
  tg_chat_id    TEXT NOT NULL DEFAULT '',
  tg_message_id INTEGER,
  tg_file_id    TEXT NOT NULL DEFAULT '',
  error         TEXT NOT NULL DEFAULT '',
  retries       INTEGER NOT NULL DEFAULT 0,
  updated_at    INTEGER NOT NULL,
  PRIMARY KEY (upload_id, idx)
);

CREATE INDEX IF NOT EXISTS idx_chunks_upload ON chunks(upload_id);
CREATE INDEX IF NOT EXISTS idx_uploads_status ON uploads(status);

-- 书籍元数据
CREATE TABLE IF NOT EXISTS books (
  id          TEXT PRIMARY KEY,
  upload_id   TEXT UNIQUE,
  title       TEXT NOT NULL DEFAULT '',
  author      TEXT NOT NULL DEFAULT '',
  description TEXT NOT NULL DEFAULT '',
  cover       TEXT NOT NULL DEFAULT '',
  format      TEXT NOT NULL DEFAULT '',
  isbn        TEXT NOT NULL DEFAULT '',
  publisher   TEXT NOT NULL DEFAULT '',
  language    TEXT NOT NULL DEFAULT '',
  file_name   TEXT NOT NULL DEFAULT '',
  file_size   INTEGER NOT NULL DEFAULT 0,
  sha256      TEXT NOT NULL DEFAULT '',
  created_by  TEXT NOT NULL DEFAULT '',
  created_at  INTEGER NOT NULL,
  updated_at  INTEGER NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_books_title ON books(title);
CREATE INDEX IF NOT EXISTS idx_books_author ON books(author);
CREATE INDEX IF NOT EXISTS idx_books_created ON books(created_at DESC);

-- 每个账号各自的评分与阅读状态
CREATE TABLE IF NOT EXISTS book_user_state (
  book_id      TEXT NOT NULL,
  user_id      TEXT NOT NULL,
  rating       REAL NOT NULL DEFAULT 0,
  status       TEXT NOT NULL DEFAULT 'unread',
  is_favorite  INTEGER NOT NULL DEFAULT 0,
  updated_at   INTEGER NOT NULL,
  PRIMARY KEY (book_id, user_id)
);

CREATE INDEX IF NOT EXISTS idx_bus_book ON book_user_state(book_id);
CREATE INDEX IF NOT EXISTS idx_bus_user ON book_user_state(user_id);

CREATE TABLE IF NOT EXISTS tags (
  id   INTEGER PRIMARY KEY AUTOINCREMENT,
  name TEXT NOT NULL UNIQUE,
  category TEXT NOT NULL DEFAULT 'other'
);

CREATE TABLE IF NOT EXISTS book_tags (
  book_id TEXT NOT NULL,
  tag_id  INTEGER NOT NULL,
  PRIMARY KEY (book_id, tag_id)
);

CREATE INDEX IF NOT EXISTS idx_book_tags_book ON book_tags(book_id);
CREATE INDEX IF NOT EXISTS idx_book_tags_tag ON book_tags(tag_id);

CREATE TABLE IF NOT EXISTS tag_dimensions (
  dimension   TEXT PRIMARY KEY,
  name_zh     TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS standard_tags (
  tag_id       TEXT PRIMARY KEY,
  name         TEXT NOT NULL,
  dimension    TEXT NOT NULL,
  category     TEXT NOT NULL DEFAULT '',
  parent_id    TEXT,
  description  TEXT NOT NULL DEFAULT '',
  status       TEXT NOT NULL DEFAULT 'active'
);

CREATE INDEX IF NOT EXISTS idx_standard_tags_dimension_status
  ON standard_tags(dimension, status, category, name);

CREATE TABLE IF NOT EXISTS standard_tag_aliases (
  alias_id INTEGER PRIMARY KEY AUTOINCREMENT,
  tag_id   TEXT NOT NULL,
  alias    TEXT NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_standard_tag_alias ON standard_tag_aliases(alias);
CREATE UNIQUE INDEX IF NOT EXISTS idx_standard_tag_alias_unique ON standard_tag_aliases(tag_id, alias);

CREATE TABLE IF NOT EXISTS book_standard_tags (
  book_id TEXT NOT NULL,
  tag_id  TEXT NOT NULL,
  PRIMARY KEY (book_id, tag_id)
);

CREATE INDEX IF NOT EXISTS idx_book_standard_tags_tag ON book_standard_tags(tag_id);

